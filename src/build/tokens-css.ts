// Generates src/styles/tokens.css from design/losoft-tokens.json.

type Named = { name: string; value: string };
type ColorToken = { name: string; value: { light: string; dark: string } };
type TypeStyle = {
  name: string;
  fontSize: string;
  lineHeight?: number;
  fontWeight: number;
  letterSpacing?: string;
  fontStyle?: string;
};
type TypeGroup = { family: string; styles: TypeStyle[] };

export type Tokens = {
  color: { tokens: ColorToken[] };
  type: { families: Record<string, string>; groups: TypeGroup[] };
  spacing: { tokens: Named[] };
  radius: { tokens: Named[] };
  fontSize: { tokens: Named[] };
  layout: { tokens: Named[] };
};

// Type style class → the fluid size variable behind it ("1em" styles keep their size).
const FLUID: Record<string, string> = {
  "t-display": "--fs-display",
  "t-h1": "--fs-h1",
  "t-h2": "--fs-h2",
  "t-h3": "--fs-h3",
  "t-lead": "--fs-lead",
  "t-body": "--fs-body",
  "t-ui": "--fs-ui",
  "t-small": "--fs-small",
  "t-label": "--fs-label",
  "t-eyebrow": "--fs-tag",
};

function vars(tokens: Named[]): string[] {
  return tokens.map((t) => `  --${t.name}: ${t.value};`);
}

function colorVars(tokens: ColorToken[], theme: "light" | "dark"): string[] {
  return tokens.map((t) => `  --${t.name}: ${t.value[theme]};`);
}

function typeClass(style: TypeStyle, family: string): string {
  const size = FLUID[style.name] ? `var(${FLUID[style.name]})` : style.fontSize;
  const lines = [`  font-family: var(--font-${family});`, `  font-size: ${size};`];
  if (style.lineHeight !== undefined) lines.push(`  line-height: ${style.lineHeight};`);
  lines.push(`  font-weight: ${style.fontWeight};`);
  if (style.letterSpacing) lines.push(`  letter-spacing: ${style.letterSpacing};`);
  if (style.fontStyle) lines.push(`  font-style: ${style.fontStyle};`);
  return `.${style.name} {\n${lines.join("\n")}\n}`;
}

export function generateTokensCss(tokens: Tokens): string {
  const light = colorVars(tokens.color.tokens, "light").join("\n");
  const dark = colorVars(tokens.color.tokens, "dark").join("\n");
  const families = Object.entries(tokens.type.families).map(
    ([name, value]) => `  --font-${name}: ${value};`,
  );
  const shared = [
    ...families,
    ...vars(tokens.fontSize.tokens),
    ...vars(tokens.spacing.tokens),
    ...vars(tokens.radius.tokens),
    ...vars(tokens.layout.tokens),
  ].join("\n");
  const classes = tokens.type.groups
    .flatMap((g) => g.styles.map((s) => typeClass(s, g.family)))
    .join("\n\n");
  return [
    "/* Generated by scripts/tokens.ts from design/losoft-tokens.json. Do not edit. */",
    `:root {\n${shared}\n  color-scheme: light dark;\n}`,
    `:root,\n:root[data-theme="light"] {\n${light}\n  color-scheme: light;\n}`,
    `@media (prefers-color-scheme: dark) {\n  :root:not([data-theme="light"]) {\n${dark.replaceAll("\n  --", "\n    --").replace("  --", "    --")}\n    color-scheme: dark;\n  }\n}`,
    `:root[data-theme="dark"] {\n${dark}\n  color-scheme: dark;\n}`,
    classes,
    "",
  ].join("\n\n");
}
